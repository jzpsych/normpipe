suppressPackageStartupMessages(library(normpipe))
inst <- read_instrument(system.file("instruments/demo7/demo7.yml", package = "normpipe"))
print(inst)
print(scale_registry(inst))
s <- get_scale(inst, "full_ab"); cat("ab grid:", length(s$grid), "dense", s$dense, "range", s$range, "step", s$step, "\n")
s <- get_scale(inst, "full_b"); cat("b grid:", head(s$grid), "... n", length(s$grid), "\n")
sim <- simulate_reference(inst, N = 1500, seed = 2)
str(sim$meta); print(sapply(sim$items, range))
sc <- score_scales(sim$items, inst)
print(summary(sc))
ref <- list(meta = sim$meta, items = sim$items)
t0 <- Sys.time()
res <- run_norming(inst, ref, out_dir = "demo-out", stages = c("P0","M1","M3a","M3b","M3c","M3d","X1"))
print(Sys.time() - t0)
print(head(res, 3)); print(table(res$cell, res$version))
